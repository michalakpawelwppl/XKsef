using System.Text.RegularExpressions;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using xKsef.Infrastructure.Persistence;

namespace xKsef.Tests.Integration;

public sealed class SqlServerTestDatabase : IAsyncLifetime
{
    private const string Server = @"(LocalDb)\MSSQLLocalDB";
    public static string DatabaseName { get; } = "xKsef_Tests_" + Guid.NewGuid().ToString("N");
    public static string ConnectionString => BuildConnection(DatabaseName);
    public string Name { get; }
    public string InstanceConnectionString => BuildConnection(Name);
    private bool _created;

    public SqlServerTestDatabase() : this(DatabaseName) { }
    private SqlServerTestDatabase(string name) { Name = name; }

    public AppDbContext CreateContext() => new(new DbContextOptionsBuilder<AppDbContext>().UseSqlServer(InstanceConnectionString).Options);

    public async Task InitializeAsync()
    {
        await CreateDatabaseAsync();
        try
        {
            await using var context = CreateContext();
            await context.Database.MigrateAsync();
        }
        catch
        {
            await DisposeAsync();
            throw;
        }
    }

    public static async Task<SqlServerTestDatabase> CreateEmptyAsync()
    {
        var database = new SqlServerTestDatabase("xKsef_Tests_" + Guid.NewGuid().ToString("N"));
        await database.CreateDatabaseAsync();
        return database;
    }

    private async Task CreateDatabaseAsync()
    {
        ValidateName();
        await using var master = new SqlConnection(BuildConnection("master"));
        await master.OpenAsync();
        using (var guard = master.CreateCommand())
        {
            guard.CommandText = "SELECT CONVERT(int, SERVERPROPERTY('IsLocalDB'))";
            if (Convert.ToInt32(await guard.ExecuteScalarAsync()) != 1)
                throw new InvalidOperationException("SQL integration tests require the isolated LocalDB server.");
        }
        using var create = master.CreateCommand();
        create.CommandText = $"CREATE DATABASE [{Name}]";
        await create.ExecuteNonQueryAsync();
        _created = true;
    }

    public static async Task VerifyAsync(string connectionString)
    {
        var target = new SqlConnectionStringBuilder(connectionString);
        if (!string.Equals(target.DataSource, Server, StringComparison.OrdinalIgnoreCase) || target.InitialCatalog != DatabaseName)
            throw new InvalidOperationException("Only this run's isolated test database is permitted.");
        await using var connection = new SqlConnection(connectionString);
        await connection.OpenAsync();
        using var guard = connection.CreateCommand();
        guard.CommandText = "SELECT CASE WHEN DB_NAME()=@database AND CONVERT(int,SERVERPROPERTY('IsLocalDB'))=1 THEN 1 ELSE 0 END";
        guard.Parameters.AddWithValue("@database", DatabaseName);
        if (Convert.ToInt32(await guard.ExecuteScalarAsync()) != 1)
            throw new InvalidOperationException("SQL test database identity verification failed.");
    }

    public async Task DisposeAsync()
    {
        if (!_created)
            return;
        ValidateName();
        SqlConnection.ClearAllPools();
        await using var master = new SqlConnection(BuildConnection("master"));
        await master.OpenAsync();
        using var drop = master.CreateCommand();
        // The name is generated by this fixture, validated, and marked owned only after CREATE succeeds.
        drop.CommandText = $"ALTER DATABASE [{Name}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{Name}];";
        await drop.ExecuteNonQueryAsync();
        _created = false;
    }

    private void ValidateName()
    {
        if (!Regex.IsMatch(Name, "^xKsef_Tests_[0-9a-f]{32}$", RegexOptions.CultureInvariant))
            throw new InvalidOperationException("Refusing to create or drop a database outside the generated test namespace.");
    }

    private static string BuildConnection(string database) => new SqlConnectionStringBuilder
    {
        DataSource = Server, InitialCatalog = database, IntegratedSecurity = true, TrustServerCertificate = true, ConnectTimeout = 10
    }.ConnectionString;
}

internal static class SqlServerTestConfiguration
{
    public static IConfigurationBuilder UseIsolatedSqlServer(this IConfigurationBuilder builder) => builder.AddInMemoryCollection(new Dictionary<string, string?>
    {
        ["ConnectionStrings:DefaultConnection"] = SqlServerTestDatabase.ConnectionString
    });
}
